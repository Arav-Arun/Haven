// Exports the DriveRegistry and VerifiableFactory ABIs and the Sepolia addresses into src/generated.ts.
// Sources: contracts/out (run `forge build` in contracts/ first) and contracts/deployments/sepolia.json,
// the single place addresses are kept. Run: pnpm --filter @haven/core gen

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getAddress, isAddress } from "viem";

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = resolve(here, "../../../contracts");
const artifactPath = resolve(contractsDir, "out/DriveRegistry.sol/DriveRegistry.json");
const factoryArtifactPath = resolve(contractsDir, "out/VerifiableFactory.sol/VerifiableFactory.json");
const deploymentPath = resolve(contractsDir, "deployments/sepolia.json");
const outPath = resolve(here, "../src/generated.ts");

for (const path of [artifactPath, factoryArtifactPath]) {
  if (!existsSync(path)) {
    console.error(`missing ${path}: run \`forge build\` in contracts/ first`);
    process.exit(1);
  }
}

const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[] };
const factoryArtifact = JSON.parse(readFileSync(factoryArtifactPath, "utf8")) as { abi: unknown[] };
const deployment = JSON.parse(readFileSync(deploymentPath, "utf8")) as Record<string, unknown>;

/** Checksums every address and drops notes (keys starting with "_"). */
function clean(value: unknown): unknown {
  if (typeof value === "string" && isAddress(value, { strict: false })) return getAddress(value);
  if (Array.isArray(value)) return value.map(clean);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !key.startsWith("_"))
        .map(([key, v]) => [key, clean(v)]),
    );
  }
  return value;
}

const source = `// Generated by \`pnpm --filter @haven/core gen\` from contracts/out and contracts/deployments/sepolia.json.
// Do not edit by hand: change the sources and run gen again.

export const driveRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const verifiableFactoryAbi = ${JSON.stringify(factoryArtifact.abi, null, 2)} as const;

export const sepoliaDeployment = ${JSON.stringify(clean(deployment), null, 2)} as const;
`;

writeFileSync(outPath, source);
console.log(`wrote ${outPath}: ${artifact.abi.length} + ${factoryArtifact.abi.length} ABI entries`);
